-- 1. PACKAGE CATEGORIES (Custom Heads: Wedding, Engagement, Pre-Wedding, Anniversary, etc.)
CREATE TABLE IF NOT EXISTS public.package_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  slug VARCHAR(150) NOT NULL UNIQUE,
  subtitle TEXT DEFAULT NULL,
  icon VARCHAR(100) DEFAULT 'fa-gem',
  order_index INT DEFAULT 0,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. PACKAGES (Packages inside each Category/Head with JSONB point-wise sections & optional dropdown descriptions)
CREATE TABLE IF NOT EXISTS public.packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES public.package_categories(id) ON DELETE CASCADE,
  name VARCHAR(200) NOT NULL,
  tagline VARCHAR(255) DEFAULT NULL,
  mrp VARCHAR(50) DEFAULT NULL,
  offer_price VARCHAR(50) NOT NULL,
  badge VARCHAR(50) DEFAULT NULL,
  is_featured BOOLEAN DEFAULT FALSE,
  sections JSONB NOT NULL DEFAULT '[]'::jsonb,
  order_index INT DEFAULT 0,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Disable RLS for backend service-role & anon queries
ALTER TABLE public.package_categories DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.packages DISABLE ROW LEVEL SECURITY;

