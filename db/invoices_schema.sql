CREATE TABLE IF NOT EXISTS public.invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_number VARCHAR(50) NOT NULL UNIQUE,
  doc_type VARCHAR(30) DEFAULT 'QUOTATION',
  client_name VARCHAR(200) NOT NULL,
  client_phone VARCHAR(50) NOT NULL,
  client_email VARCHAR(200) DEFAULT NULL,
  event_type VARCHAR(100) DEFAULT 'Wedding',
  event_dates VARCHAR(200) DEFAULT NULL,
  venue VARCHAR(255) DEFAULT NULL,
  package_title VARCHAR(200) DEFAULT 'Custom Wedding Package',
  day_wise_plan JSONB NOT NULL DEFAULT '[]'::jsonb,
  deliverables JSONB NOT NULL DEFAULT '[]'::jsonb,
  mrp_total NUMERIC(12, 2) DEFAULT 0,
  discount NUMERIC(12, 2) DEFAULT 0,
  final_amount NUMERIC(12, 2) DEFAULT 0,
  advance_paid NUMERIC(12, 2) DEFAULT 0,
  notes TEXT DEFAULT NULL,
  terms TEXT DEFAULT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.invoices DISABLE ROW LEVEL SECURITY;
